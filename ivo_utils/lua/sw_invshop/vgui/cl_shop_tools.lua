concommand.Add("sw_shop_pos_weapon", function(ply)
    local pos = ply:EyePos()
    local ang = ply:EyeAngles()
    print("\n==================================")
    print("NUEVAS COORDENADAS PARA EL ARMA:")
    print("SW_InvShop.Config3D_WeaponPos = Vector("..pos.x..", "..pos.y..", "..pos.z..")")
    print("SW_InvShop.Config3D_WeaponAng = Angle(0, "..ang.y..", 0)")
    print("¡Cópialas y pégalas en la parte superior de cl_3d_shop.lua!")
    print("==================================\n")
    ply:ChatPrint("Coordenadas del Arma impresas en tu Consola.")
end)

